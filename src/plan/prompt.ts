import { readFile } from 'node:fs/promises'
import path from 'node:path'

export const SYSTEM_PROMPT = `你是一个前端技术教学视频的编剧。

你会拿到一篇文章，要把它改写成一段讲解视频的旁白（讲稿），并同时决定画面上出现什么。

你的输出会被程序直接解析并逐条校验。所以你只输出一个 JSON 对象，不要任何解释文字。`

// 把范例读进来当 few-shot。
// 用真实产物当范例，比在提示词里手写一段更不容易和格式脱节。
async function loadExample(): Promise<string> {
  return (await readFile(path.resolve('corpus/example-episode.json'), 'utf8')).trim()
}

export async function buildUserPrompt(article: string): Promise<string> {
  const example = await loadExample()

  return `# 输出格式

严格输出一个 JSON 对象：

{
  "parts": [ { "text": "……" }, ... ],
  "scenes": [ { "template": "……", "startPart": 数字, "props": { ... } }, ... ]
}

## parts —— 旁白被切成一段一段

- parts 里的 text **按顺序拼起来就是完整旁白**。不要漏字、不要多字。
- 每段**一句话**，15 到 30 字，一口气能念完。
- 标点照常写（逗号、句号、问号），它们会影响朗读的停顿。
- 不要写 Markdown 记号（# * - >），不要写括号编号。
- 英文和数字可以直接写（Vue3、ref、value），朗读引擎会念出来。

## 画面靠「段号」对齐

**讲稿的每一段都有一个编号，从 0 开始。**

画面元素写 "part": 3，意思就是「念到第 3 段的时候，这个元素出现」。

这是整套东西的核心：
- 段号是**程序数出来的**，你只要数对，**不需要给任何东西起名字**。
- 幻灯片里的**每一条要点**都要写 part，指向**专门讲这条要点的那一段**。
- 代码块里的**每一行**（除了纯收尾符号）都要写 part，指向专门讲这一行的那一段。

### SlideBullets（幻灯片）

{
  "template": "SlideBullets",
  "startPart": 0,
  "props": {
    "title": "幻灯片标题",
    "bullets": [
      { "text": "要点文字", "part": 0 },
      { "text": "另一条要点", "part": 3 }
    ]
  }
}

### CodeTyping（代码逐字打出）

{
  "template": "CodeTyping",
  "startPart": 4,
  "props": {
    "fileName": "demo.js",
    "lines": [
      { "code": "const a = ref(0)", "part": 5 },
      { "code": "console.log(a.value)", "part": 6 },
      { "code": "  }" }
    ]
  }
}

# 硬性要求

1. **段号只能往上走**：
   - startPart 必须小于等于这个场景里所有元素引用的 part。
   - 同一个场景里，元素的 part 不能倒退（可以相等，表示同时出现）。
   - 场景之间的 startPart 必须**严格递增**。
   一句话：**从上往下读，段号只能变大，不能变小、不能相等。**

2. **代码必须「讲一行、出现一行」**：除了纯收尾符号（} / }) / );），
   每一行代码都要有自己的 part，而且讲稿里那一段要讲的**正是这一行代码**。
   最常见的致命错误：代码写了 7 行，讲稿却只讲了 4 句 —— 剩下 3 行会自己按打字速度冒出来，
   声音和画面就彻底错开了。代码不多写、讲解不缺席，两边数量要对上。

3. **画面装得下的上限（超过直接校验失败）**：
   - 一页幻灯片最多 6 条要点，每条最多 22 个字；标题最多 20 个字。
   - 一个代码场景最多 8 行，每行最多 60 个字符（超了会被裁掉）。
   - 每段旁白最多 55 个字。
   装不下就**拆成两页或两个场景**，不要硬塞。

4. 全片 1 到 3 分钟。按每秒 5.3 个字估算，也就是大约 300 到 900 字。
   **900 字是硬上限，超过直接校验失败。**
   文章往往能讲十分钟，但视频只能讲两分钟 —— 所以你必须做取舍：
   先通读文章，挑出**最有价值的 2 到 3 个点**，只讲这些，其余整段舍弃。
   宁可少讲、讲透，不要全而浅。被舍弃的内容，观众可以回去看原文。
5. 代码必须是**正确、可运行**的代码，不要混入过时写法。
6. 讲稿要口语化，像老师在讲课，不要照念文档。
7. 每个场景的**第一条内容要在场景开始后 3 秒内出现**，不要开场只有标题干等。
8. **每个场景要「装得下」自己引用的内容**：
   - 一个场景最多覆盖 6 段讲稿（挂太久观众以为卡住了）。
   - 场景里引用的段号**不能超过下一个场景的开始段** —— 超了那个元素永远不会出现。
   一句话：**讲几件事，就配几个场景，每个场景的时间要够它自己的内容演完。**
9. 一般 3 到 6 个场景：先用幻灯片交代脉络，再用代码场景讲细节。

# 一个已经做好的范例

${example}

# 现在轮到你

把下面这篇文章，按同样的格式改写成讲稿和分镜。

<文章>
${article}
</文章>

只输出 JSON。`
}