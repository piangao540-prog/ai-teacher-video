import { readFile } from 'node:fs/promises'
import path from 'node:path'
import type { SourceKind } from './source'

export const SYSTEM_PROMPT = `你是一个前端技术教学视频的编剧。

你会拿到一份素材：可能是一篇文章，也可能是一句话的主题。
不管拿到哪种，你要做的事都一样 —— 像老师一样，把这个知识点讲明白：
写出一段讲解视频的旁白（讲稿），并同时决定画面上出现什么。

你的输出会被程序直接解析并逐条校验。所以你只输出一个 JSON 对象，不要任何解释文字。`

// 把范例读进来当 few-shot。
// 用真实产物当范例，比在提示词里手写一段更不容易和格式脱节。
async function loadExample(): Promise<string> {
  return (await readFile(path.resolve('corpus/example-episode.json'), 'utf8')).trim()
}

// 素材是文章还是主题，只有这一处分叉 —— 而且分叉放在 user 消息里，紧贴着标签。
//
// 为什么不写成正文里的一句「如果素材是一篇文章……如果只是一句话主题……」：
// 那样模型每次都得先判断自己拿到的是哪种，判断错了整段就歪；
// 而这么写，模型永远不做分类，它只是读一个标签、读一句已经确定的引导。
// 更重要的是，不变量（300–900 字、2 到 3 个点、段号对齐、JSON 格式）
// 仍然只存在于提示词正文的**一处** —— 条件句写进正文的话，
// 将来改「2 到 3 个点」就得去动一句和分支文本纠缠在一起的散文，漂就是这么开始的。
const LEAD: Record<SourceKind, string> = {
  topic:
    '下面是**一句话主题**，没有原文。由你决定讲哪 2 到 3 个点 —— ' +
    '挑「初学者最容易卡住的地方」，而不是「最全的知识点清单」。' +
    '先讲它**解决什么问题**，再给一个**最小能跑通的例子**，最后讲**最容易搞错的地方**。',
  article: '下面是一篇**文章**。先通读，挑出最有价值的 2 到 3 个点，只讲这些，其余整段舍弃。',
}

// 标签名是唯一的判别点：模型读的是 <主题> 还是 <文章>，不用猜。
const TAG: Record<SourceKind, string> = { topic: '主题', article: '文章' }

export async function buildUserPrompt(source: string, kind: SourceKind): Promise<string> {
  const example = await loadExample()

  return `# 输出格式

严格输出一个 JSON 对象：

{
  "parts": [ { "text": "……" }, ... ],
  "scenes": [ { "template": "……", "startPart": 数字, "props": { ... } }, ... ]
}

## parts —— 旁白被切成一段一段

- parts 里的 text **按顺序拼起来就是完整旁白**。不要漏字、不要多字。
- 每段**一句话**，15 到 30 字，一口气能念完。
- 标点照常写（逗号、句号、问号），它们会影响朗读的停顿。
- 不要写 Markdown 记号（# * - >），不要写括号编号。
- 英文和数字可以直接写（Vue3、ref、value），朗读引擎会念出来。

## 画面靠「段号」对齐

**讲稿的每一段都有一个编号，从 0 开始。**

画面元素写 "part": 3，意思就是「念到第 3 段的时候，这个元素出现」。

这是整套东西的核心：
- 段号是**程序数出来的**，你只要数对，**不需要给任何东西起名字**。
- 幻灯片里的**每一条要点**都要写 part，指向**专门讲这条要点的那一段**。
- 代码块里的**每一行**（除了纯收尾符号）都要写 part，指向专门讲这一行的那一段。
- 终端里的**每条命令**都要写 part；输出行不写 part，它紧跟在自己那条命令后面出现。

### SlideBullets（幻灯片）

{
  "template": "SlideBullets",
  "startPart": 0,
  "props": {
    "title": "幻灯片标题",
    "bullets": [
      { "text": "要点文字", "part": 0 },
      { "text": "另一条要点", "part": 3 }
    ]
  }
}

### CodeTyping（代码逐字打出）

{
  "template": "CodeTyping",
  "startPart": 4,
  "props": {
    "fileName": "demo.js",
    "lines": [
      { "code": "const a = ref(0)", "part": 5 },
      { "code": "console.log(a.value)", "part": 6 },
      { "code": "  }" }
    ]
  }
}

### Terminal（终端演示）

{
  "template": "Terminal",
  "startPart": 8,
  "props": {
    "title": "运行构建",
    "prompt": "$",
    "lines": [
      { "text": "pnpm build", "kind": "command", "part": 9 },
      { "text": "✓ built in 363ms", "kind": "output" },
      { "text": "pnpm dev", "kind": "command", "part": 10 },
      { "text": "➜  Local: http://localhost:5173/", "kind": "output" }
    ]
  }
}

# 硬性要求

1. **段号只能往上走**：
   - startPart 必须小于等于这个场景里所有元素引用的 part。
   - 同一个场景里，元素的 part 不能倒退（可以相等，表示同时出现）。
   - 场景之间的 startPart 必须**严格递增**。
   一句话：**从上往下读，段号只能变大，不能变小、不能相等。**

2. **代码必须「讲一行、出现一行」**：除了纯收尾符号（} / }) / );），
   每一行代码都要有自己的 part，而且讲稿里那一段要讲的**正是这一行代码**。
   最常见的致命错误：代码写了 7 行，讲稿却只讲了 4 句 —— 剩下 3 行会自己按打字速度冒出来，
   声音和画面就彻底错开了。代码不多写、讲解不缺席，两边数量要对上。
   Terminal 同理：**每条命令都要有自己的 part**，输出行不写 part（它紧跟命令之后出现）。

3. **画面装得下的上限（超过直接校验失败）**：
   - 一页幻灯片最多 6 条要点，每条最多 22 个字；标题最多 20 个字。
   - 一个代码场景（CodeTyping）或终端场景（Terminal）最多 8 行，每行最多 60 个字符。
   - 每段旁白最多 55 个字。
   装不下就**拆成两页或两个场景**，不要硬塞。

4. **目标 800 到 900 字** —— 按每秒 5.3 个字估算约 2 分半。
   宁可写到顶格，也不要只写一半：范围的下沿不是给你贴的。
   **900 字是硬上限，300 字是下限，超出直接校验失败。**
   只讲 **2 到 3 个点**：砍掉的是**次要的点**，不是留下来那个点的**展开**。
   宁可讲透一个点，也不要三个点都点到为止。
   素材往往够讲十分钟，但视频只有两分钟 —— 讲不完的，本来也不该塞进一集。
5. 代码必须是**正确、可运行**的代码，不要混入过时写法。
   拿不准 API 名或版本号，就只写大版本、或者干脆不写具体版本号，**绝不编造 API**。
6. 讲稿要口语化，像老师在讲课，不要照念文档。
7. 每个场景的**第一条内容要在场景开始后 3 秒内出现**，不要开场只有标题干等。
8. **每个场景要「装得下」自己引用的内容**：
   - 一个场景最多覆盖 6 段讲稿（挂太久观众以为卡住了）。
   - 场景里引用的段号**不能超过下一个场景的开始段** —— 超了那个元素永远不会出现。
   一句话：**讲几件事，就配几个场景，每个场景的时间要够它自己的内容演完。**
9. 一般 3 到 6 个场景：先用幻灯片交代脉络，再用代码场景讲细节。
   要展示「把它跑起来会发生什么」（构建输出、起服务、测试结果），就用 Terminal ——
   Terminal 讲的是运行结果，CodeTyping 讲的是代码本身，别拿 Terminal 去念代码。

# 一个已经做好的范例

${example}

# 现在轮到你

${LEAD[kind]}

<${TAG[kind]}>
${source}
</${TAG[kind]}>

按上面的格式写出讲稿和分镜。只输出 JSON。`
}